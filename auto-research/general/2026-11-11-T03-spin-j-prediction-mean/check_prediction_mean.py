#!/usr/bin/env python3
"""Exact rational checks for the spin-j bond-tag prediction mean (SU(2)).

Standard library only.  Unit quaternions with rational coordinates are
generated by stereographic projection, so every identity below is tested in
exact arithmetic.  Integer spins j = 1, 2 are used because rho_j(M/|M|) is
then rational; half-integer spins are not covered by this exact checker.

Nothing here bounds a spatial covariance or replays the upstream source.
"""
import json
import random
import sys
from fractions import Fraction as Fr
from math import isqrt

FAILURES = []
rng = random.Random(20261111)


def check(name, ok):
    if not ok:
        FAILURES.append(name)
    return bool(ok)


# ------------------------------------------------------------ quaternions
def qmul(a, b):
    return (a[0]*b[0] - a[1]*b[1] - a[2]*b[2] - a[3]*b[3],
            a[0]*b[1] + a[1]*b[0] + a[2]*b[3] - a[3]*b[2],
            a[0]*b[2] - a[1]*b[3] + a[2]*b[0] + a[3]*b[1],
            a[0]*b[3] + a[1]*b[2] - a[2]*b[1] + a[3]*b[0])


def qconj(a):
    return (a[0], -a[1], -a[2], -a[3])


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def unit_from(t):
    """Rational point of S^3 from a rational 3-vector."""
    n = sum(x*x for x in t)
    return ((1 - n)/(1 + n),) + tuple(2*x/(1 + n) for x in t)


def rand_unit(scale=3, den=7):
    return unit_from([Fr(rng.randint(-scale*den, scale*den), den) for _ in range(3)])


def rand_near(center, spread_den):
    g = unit_from([Fr(rng.randint(-3, 3), spread_den) for _ in range(3)])
    return qmul(center, g)


def rand_weights(k):
    raw = [rng.randint(1, 9) for _ in range(k)]
    s = sum(raw)
    return [Fr(x, s) for x in raw]


def sqrt_upper(x, digits=40):
    """Rational upper bound for sqrt of a nonnegative rational."""
    scale = 10**digits
    return Fr(isqrt(int(x*scale*scale)) + 1, scale)


# ------------------------------------------------------------ matrices
def mat(n, m, f):
    return [[f(i, j) for j in range(m)] for i in range(n)]


def mmul(a, b):
    return [[sum(a[i][k]*b[k][j] for k in range(len(b))) for j in range(len(b[0]))]
            for i in range(len(a))]


def madd(a, b, s=1):
    return [[x + s*y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]


def mscale(a, c):
    return [[c*x for x in row] for row in a]


def mT(a):
    return [list(r) for r in zip(*a)]


def trace(a):
    return sum(a[i][i] for i in range(len(a)))


def rot_tilde(q):
    """Quadratic extension of the spin-1 (rotation) matrix; equals |q|^2 R."""
    w, x, y, z = q
    return [[w*w + x*x - y*y - z*z, 2*(x*y - w*z), 2*(x*z + w*y)],
            [2*(x*y + w*z), w*w - x*x + y*y - z*z, 2*(y*z - w*x)],
            [2*(x*z - w*y), 2*(y*z + w*x), w*w - x*x - y*y + z*z]]


def rot_normalized(q):
    return mscale(rot_tilde(q), 1/dot(q, q))


# spin 2: conjugation S -> R S R^T on symmetric traceless 3x3 matrices,
# in the rational (non-orthonormal) basis below with Gram matrix H2.
BASIS2 = []
for (i, j) in ((0, 1), (0, 2), (1, 2)):
    BASIS2.append(mat(3, 3, lambda a, b, i=i, j=j: Fr(1) if (a, b) in ((i, j), (j, i)) else Fr(0)))
BASIS2.append(mat(3, 3, lambda a, b: Fr(1) if a == b == 0 else Fr(-1) if a == b == 1 else Fr(0)))
BASIS2.append(mat(3, 3, lambda a, b: Fr(1) if a == b == 1 else Fr(-1) if a == b == 2 else Fr(0)))
H2 = mat(5, 5, lambda a, b: trace(mmul(BASIS2[a], mT(BASIS2[b]))))
H1 = mat(3, 3, lambda a, b: Fr(int(a == b)))


def coords2(s):
    return [s[0][1], s[0][2], s[1][2], s[0][0], -s[2][2]]


def spin2_from_rot(r):
    cols = [coords2(mmul(mmul(r, b), mT(r))) for b in BASIS2]
    return mT(cols)


def rep(j, q_normalized_rot):
    return q_normalized_rot if j == 1 else spin2_from_rot(q_normalized_rot)


def is_pos_def(a):
    """Exact test by elimination pivots (symmetric rational matrix)."""
    a = [row[:] for row in a]
    n = len(a)
    for k in range(n):
        if a[k][k] <= 0:
            return False
        for i in range(k + 1, n):
            f = a[i][k]/a[k][k]
            for c in range(k, n):
                a[i][c] -= f*a[k][c]
    return True


def gamma(j):
    """Proved constant (2j)^2 in ||rho_j(u) - sum_x w_x rho_j(Y_x)|| <= gamma (1-r)."""
    return Fr(2*j)**2


def sharpness():
    """Pair exp(+-t i), weights 1/2, spin 1: the ratio is exactly 2(1 + cos t)."""
    rows = []
    for den in (10, 1000, 100000):
        tau = Fr(1, den)
        c, s_ = (1 - tau*tau)/(1 + tau*tau), 2*tau/(1 + tau*tau)
        g, gi = (c, s_, Fr(0), Fr(0)), (c, -s_, Fr(0), Fr(0))
        avg = madd(mscale(rot_normalized(g), Fr(1, 2)), mscale(rot_normalized(gi), Fr(1, 2)))
        err = madd(mat(3, 3, lambda a, b: Fr(int(a == b))), avg, -1)
        diagonal = all(err[a][b] == 0 for a in range(3) for b in range(3) if a != b)
        ratio = max(err[k][k] for k in range(3))/(1 - c)   # r = c here
        ok = check("sharpness", diagonal and ratio == 2*(1 + c) and ratio < 4)
        rows.append({"tan_half_t": str(tau), "ratio": f"{float(ratio):.12f}",
                     "equals_2(1+cos t)_and_below_4": ok})
    return rows


def family(kind):
    k = rng.randint(2, 6)
    w = rand_weights(k)
    if kind == "spread":
        ys = [rand_unit() for _ in range(k)]
    else:
        c = rand_unit()
        ys = [rand_near(c, {"tight": 40, "medium": 6}[kind]) for _ in range(k)]
    return w, ys


def mean_q(w, ys):
    return tuple(sum(wi*y[i] for wi, y in zip(w, ys)) for i in range(4))


# ------------------------------------------------------------ checks
def cost_identity():
    n_ok = 0
    for _ in range(200):
        w, ys = family(rng.choice(["spread", "medium", "tight"]))
        m = mean_q(w, ys)
        u = rand_unit()
        cost = sum(wi*(1 - qmul(y, qconj(u))[0]) for wi, y in zip(w, ys))
        ok = cost == 1 - dot(m, u) and dot(m, u)**2 <= dot(m, m)
        n_ok += check("cost identity", ok)
    return {"cases": 200, "passed": n_ok,
            "claim": "bondCost(Y,u) = 1 - <M,u> and <M,u>^2 <= |M|^2"}


def not_function_of_mean():
    one, i = (Fr(1), Fr(0), Fr(0), Fr(0)), (Fr(0), Fr(1), Fr(0), Fr(0))
    neg = lambda q: tuple(-x for x in q)
    fam_a = ([Fr(1, 2)]*2, [one, neg(one)])
    fam_b = ([Fr(1, 4)]*4, [one, i, neg(one), neg(i)])
    out = {}
    for name, (w, ys) in (("a", fam_a), ("b", fam_b)):
        d1 = [[sum(wi*rot_normalized(y)[r][c] for wi, y in zip(w, ys)) for c in range(3)]
              for r in range(3)]
        out[name] = {"mean": [str(x) for x in mean_q(w, ys)],
                     "D_1_diagonal": [str(d1[k][k]) for k in range(3)]}
    ok = (out["a"]["mean"] == out["b"]["mean"] == ["0"]*4
          and out["a"]["D_1_diagonal"] != out["b"]["D_1_diagonal"])
    out["same_mean_different_D_1"] = check("D_1 not a function of M", ok)
    return out


def truncation_bound():
    out = {}
    for j, hmat in ((1, H1), (2, H2)):
        g = gamma(j)
        rows = {"constant_(2j)^2": str(g), "cases": 0, "bound_holds": 0,
                "skipped_small_mean": 0}
        for kind in ("spread", "medium", "tight"):
            for _ in range(120):
                w, ys = family(kind)
                m = mean_q(w, ys)
                r2 = dot(m, m)
                if r2 < Fr(1, 10**6) or r2 == 1:
                    rows["skipped_small_mean"] += 1
                    continue
                r_hi = sqrt_upper(r2)
                if r_hi >= 1:
                    rows["skipped_small_mean"] += 1
                    continue
                best = rep(j, rot_normalized(m))
                size = len(best)
                lin = [[Fr(0)]*size for _ in range(size)]
                for wi, y in zip(w, ys):
                    lin = madd(lin, mscale(rep(j, rot_normalized(y)), wi))
                err = madd(best, lin, -1)
                ehe = mmul(mmul(mT(err), hmat), err)
                delta = 1 - r_hi          # rational lower bound for 1 - r
                rows["cases"] += 1
                rows["bound_holds"] += check(
                    f"(2j)^2 bound j={j}",
                    is_pos_def(madd(mscale(hmat, (g*delta)**2), ehe, -1)))
        out[f"j={j}"] = rows
    return out


def half_trace_sq(q):
    """(1/2) Tr(q^2) for a quaternion q (not necessarily unit)."""
    return qmul(q, q)[0]


def repeated_link():
    """Loop V1 V2 traversed twice: (1/2)Tr((V1 V2)^2) = (chi_1(V1 V2) - 1)/2."""
    results = []
    cut = Fr(1, 20)
    for _ in range(60):
        fams = [family(rng.choice(["spread", "medium", "tight"])) for _ in range(2)]
        tags, means, branches = [], [], []
        for w, ys in fams:
            m = mean_q(w, ys)
            r2 = dot(m, m)
            uses_best = r2 > (1 - cut)**2          # 1 - r < cut, exactly
            branches.append(uses_best)
            if uses_best:
                # every tag predicts M/r; tag masses sum to one
                tags.append([(Fr(1), ("normalized", m, r2))])
                means.append(rot_normalized(m))
            else:
                tags.append([(wi, ("plain", y, Fr(1))) for wi, y in zip(w, ys)])
                d1 = [[Fr(0)]*3 for _ in range(3)]
                for wi, y in zip(w, ys):
                    d1 = madd(d1, mscale(rot_normalized(y), wi))
                means.append(d1)
        direct = Fr(0)
        for w1, (_, q1, n1) in tags[0]:
            for w2, (_, q2, n2) in tags[1]:
                # prediction = q/|q|; (1/2)Tr((p1 p2)^2) = 2 Re(p1 p2)^2 - 1
                re2 = qmul(q1, q2)[0]**2/(n1*n2)
                direct += w1*w2*(2*re2 - 1)
        sector = (trace(mmul(means[0], means[1])) - 1)/2
        ok = check("repeated link sector formula", direct == sector)
        results.append((ok, tuple(branches)))
    # the naive rule squares the fundamental mean instead
    w, ys = family("spread")
    w2, ys2 = family("spread")
    m1, m2 = mean_q(w, ys), mean_q(w2, ys2)
    naive = half_trace_sq(qmul(m1, m2))
    direct = sum(a*b*(2*qmul(y, z)[0]**2 - 1)
                 for a, y in zip(w, ys) for b, z in zip(w2, ys2))
    return {"cases": len(results), "passed": sum(ok for ok, _ in results),
            "branch_pairs_seen": sorted({str(b) for _, b in results}),
            "naive_fundamental_mean_rule_differs":
                check("naive rule differs", naive != direct),
            "example_direct": str(direct), "example_naive": str(naive)}


def main():
    report = {
        "scope": ("exact rational checks of the SU(2) bond-tag prediction mean "
                  "for integer spins; no spatial covariance bound, no upstream "
                  "replay, no Lean proof"),
        "seed": 20261111,
        "constant_(2j)^2": {"1/2": str(gamma(Fr(1, 2))), "1": str(gamma(1)),
                            "3/2": str(gamma(Fr(3, 2))), "2": str(gamma(2))},
        "cost_identity": cost_identity(),
        "fallback_mean_not_a_function_of_M": not_function_of_mean(),
        "truncation_bound": truncation_bound(),
        "sharpness_spin_1": sharpness(),
        "repeated_link": repeated_link(),
    }
    report["failures"] = FAILURES
    report["all_passed"] = not FAILURES
    json.dump(report, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0 if not FAILURES else 1


if __name__ == "__main__":
    sys.exit(main())
